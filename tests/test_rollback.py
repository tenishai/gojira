def _web_client(tmp_path, clients):
    from fastapi.testclient import TestClient

    from gojira.web import create_app

    engine = create_engine(
        f"sqlite:///{tmp_path}/gojira.db", connect_args={"check_same_thread": False}
    )
    Base.metadata.create_all(engine)
    sf = sessionmaker(bind=engine, expire_on_commit=False)
    with sf() as s:
        app, cluster = _active_app(s)
        app_id, ar_repo = app.id, cluster.ar_repo
    return TestClient(create_app(sf, clients=clients)), app_id, ar_repo


def test_history_page_lists_deploys_with_rollback_buttons(tmp_path):
    runs = [
        {"sha": "b" * 40, "title": "newer", "finished_at": "t2", "run_url": "u2"},
        {"sha": SHA, "title": "older", "finished_at": "t1", "run_url": "u1"},
    ]
    clients = _clients(FakeGitHubClient(deploy_history=runs), FakeGCPClient())
    web, app_id, _ = _web_client(tmp_path, clients)

    plain = web.get(f"/apps/{app_id}").text
    assert "Show recent deploys" in plain and "Roll back to this" not in plain

    page = web.get(f"/apps/{app_id}?history=1").text
    assert TAG in page and "older" in page
    assert page.count("Roll back to this") == 1  # newest is "latest", no button
    assert "latest" in page


def test_rollback_route_applies_and_flashes_the_notice(tmp_path):
    github = RepoTreeGitHub()
    # The digest key needs ar_repo, known only after registration — preset the
    # dict object and fill it in after _web_client registers the cluster.
    gcp = FakeGCPClient()
    clients = _clients(github, gcp)
    web, app_id, ar_repo = _web_client(tmp_path, clients)
    gcp.image_digests[f"{ar_repo}/a:{TAG}"] = DIGEST

    # The real route renders via kubectl kustomize; the fixture tree has no
    # base/, so patch the renderer at the service seam.
    import gojira.service as svc

    orig = svc.kustomize_build
    svc.kustomize_build = lambda overlay: [
        {"kind": "Deployment", "metadata": {"name": "a", "namespace": "ns"}}
    ]
    try:
        r = web.post(f"/apps/{app_id}/rollback", data={"sha": SHA}, follow_redirects=True)
    finally:
        svc.kustomize_build = orig

    assert r.status_code == 200
    assert "now runs " + TAG in r.text.replace("&#39;", "'")
    kubectl = next(iter(clients.kubectl_for.by_cluster.values()))
    assert any("kind: Deployment" in m for m in kubectl.applied)


def test_rollback_route_surfaces_errors_on_the_history_page(tmp_path):
    clients = _clients(RepoTreeGitHub(), FakeGCPClient())  # no digest -> refusal
