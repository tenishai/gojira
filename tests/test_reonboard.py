"""Re-onboarding must preserve operator state and conclude gracefully.

Finding #8 from the teardown/recreate dogfood: connecting an app whose repo
was already Gojira-configured (a) regenerated the overlay kustomization and
silently DROPPED the drift-capture patch wiring — reverting captured cluster
state on the next deploy — and (b) open_setup_pr raised 'nothing to commit'
when the render matched main instead of concluding the app is active.
"""

import pytest
import yaml
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker

from gojira.config import Config
from gojira.generator import preserve_patches
from gojira.models import App, AppStatus, Base, Cluster, Environment
from gojira.provisioner import provision_app
from tests.fakes import FakeGCPClient, FakeGitHubClient, KubectlFactory

RENDERED = """\
# Generated by Gojira. The image tag is set by CI at deploy time
# (kustomize edit set image) — don't pin it by hand.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: gojira-demo
resources:
  - ../../base
labels:
  - pairs:
      gojira.dev/env: dev
images:
  - name: gojira-app
    newName: us-central1-docker.pkg.dev/example/apps/gojira-demo
    newTag: latest
"""

EXISTING_WITH_PATCH = """\
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: gojira-demo
resources:
- ../../base
images:
- name: gojira-app
  newName: us-central1-docker.pkg.dev/example/apps/gojira-demo
  newTag: latest
patches:
- path: drift-gojira-demo.yaml
"""


def test_drift_patch_survives_regeneration():
    out = preserve_patches(EXISTING_WITH_PATCH, RENDERED)
    parsed = yaml.safe_load(out)
    assert parsed["patches"] == [{"path": "drift-gojira-demo.yaml"}]
    assert "# Generated by Gojira" in out          # render comments intact
    assert parsed["resources"] == ["../../base"]   # render owns everything else


def test_no_patches_means_untouched_render():
    assert preserve_patches(RENDERED, RENDERED) == RENDERED


def test_unparseable_existing_regenerates_clean():
    assert preserve_patches(":\n  not yaml: [", RENDERED) == RENDERED


def test_duplicate_patch_paths_not_doubled():
    rendered_with = RENDERED + "patches:\n  - path: drift-gojira-demo.yaml\n"
    out = preserve_patches(EXISTING_WITH_PATCH, rendered_with)
    assert out.count("drift-gojira-demo.yaml") == 1


# --- the orchestrator half: nothing-to-commit concludes ACTIVE ---------------


class UpToDateGitHub(FakeGitHubClient):
    """A repo whose default branch already matches the render exactly."""

    def commit_all(self, workdir, message):
        self.calls.append("commit")
        return False  # git saw no diff


@pytest.fixture
def session():
    engine = create_engine("sqlite://")
    Base.metadata.create_all(engine)
    with sessionmaker(bind=engine, expire_on_commit=False)() as s:
        yield s


def _seed(session):
    c = Cluster(name="sandbox", gcp_project="example-project", location="us-central1",
                gke_cluster="g", ar_repo="us-central1-docker.pkg.dev/example-project/apps")
    session.add(c)
    session.commit()
    a = App(name="gojira-demo", repo_full_name="acme/gojira-demo",
            installation_id=1, workload_class="web",
            setup_pr_url="https://github.com/acme/gojira-demo/pull/3")  # stale, merged long ago
    session.add(a)
    session.commit()
    session.add(Environment(app_id=a.id, name="dev", cluster_id=c.id, namespace="demo"))
    session.commit()
    return a


def test_reonboard_of_configured_repo_goes_active(session, tmp_path):
    app = _seed(session)
    result = provision_app(
        session, app,
        gcp=FakeGCPClient(), github=UpToDateGitHub(),
        kubectl_for=KubectlFactory(), config=Config(), workdir=tmp_path,
    )
    assert result.completed
    assert app.status == AppStatus.ACTIVE       # not AWAITING_PR, not FAILED
    assert app.setup_pr_url is None             # stale URL cleared


def test_first_onboard_still_awaits_pr(session, tmp_path):
    app = _seed(session)
    app.setup_pr_url = None
    session.commit()
    result = provision_app(
        session, app,
        gcp=FakeGCPClient(), github=FakeGitHubClient(),  # commit_all -> True
        kubectl_for=KubectlFactory(), config=Config(), workdir=tmp_path,
    )
    assert result.completed
    assert app.status == AppStatus.AWAITING_PR
    assert app.setup_pr_url and "/pull/" in app.setup_pr_url

def test_rename_drops_orphaned_patch_but_keeps_live_one(tmp_path):
    """Finding #10 (rename half): a preserved patch whose target the render no
    longer produces (app renamed) must be dropped — kustomize hard-fails the
    whole build on an orphaned patch. A patch targeting a still-rendered
    object survives."""
    from gojira.generator import preserve_patches
    from gojira.steps import _patch_targets_rendered, _rendered_targets

    files = {
        "k8s/base/deployment.yaml":
            "apiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: new-name\n",
    }
    rendered = _rendered_targets(files)

    overlay = tmp_path
    (overlay / "drift-old.yaml").write_text(
        "kind: Deployment\nmetadata:\n  name: old-name\n")
    (overlay / "drift-new.yaml").write_text(
        "kind: Deployment\nmetadata:\n  name: new-name\n")
    existing = "resources:\n- ../../base\npatches:\n- path: drift-old.yaml\n- path: drift-new.yaml\n"

    out = preserve_patches(
        existing, RENDERED,
        keep_path=lambda p: _patch_targets_rendered(overlay / p, rendered),
    )
    assert "drift-new.yaml" in out       # live target: kept
    assert "drift-old.yaml" not in out   # orphaned by rename: dropped


def test_retry_refreshes_an_open_setup_pr(session, tmp_path):
    """Finding #13: a Retry after a generator upgrade must force-push fresh
    content under the OPEN setup PR — not skip because the PR exists (which
    silently discarded the regenerated tree on the first real tenant)."""
    app = _seed(session)
    gh = FakeGitHubClient(
        existing_pr="https://github.com/acme/gojira-demo/pull/3")  # PR open, stale
    result = provision_app(
        session, app,
        gcp=FakeGCPClient(), github=gh,
        kubectl_for=KubectlFactory(), config=Config(), workdir=tmp_path,
    )
    assert result.completed
    assert gh.pushed is not None                      # branch force-pushed
    assert not [c for c in gh.calls if c.startswith("open_pr")]                  # no duplicate PR
    assert app.status == AppStatus.AWAITING_PR
    assert app.setup_pr_url == "https://github.com/acme/gojira-demo/pull/3"


def test_second_provision_run_still_refreshes_the_pr(session, tmp_path):
    """Finding #13's real root: the DONE ledger row from the first run must not
    skip open_setup_pr on a Retry — the step is ephemeral, like the workdir
    steps, because the ledger cannot know whether the branch matches a newer
    render. Two runs: one PR opened, two pushes."""
    app = _seed(session)
    app.setup_pr_url = None
    session.commit()
    gh = FakeGitHubClient()
    for _ in (1, 2):
        result = provision_app(
            session, app,
            gcp=FakeGCPClient(), github=gh,
            kubectl_for=KubectlFactory(), config=Config(), workdir=tmp_path,
        )
        assert result.completed
    assert len([c for c in gh.calls if c.startswith("open_pr")]) == 1
    assert len([c for c in gh.calls if c.startswith("push")]) == 2
    assert app.setup_pr_url and "/pull/" in app.setup_pr_url
