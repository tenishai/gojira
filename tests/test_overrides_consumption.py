"""Overrides consumption: the justified escape hatch actually reshapes manifests.

Three seams: render() honors GeneratorSpec.overrides (so regeneration never
reverts sizing — the finding-8 lesson applied to sizing); read_overrides()
parses the gojira.yaml block defensively; apply_resource_overrides() rewrites
a generated deployment textually for the one-PR sizing flow.
"""

import yaml

from gojira.generator import (
    EnvSpec,
    GeneratorSpec,
    Overrides,
    apply_resource_overrides,
    read_overrides,
    render,
)


def _spec(overrides=None):
    return GeneratorSpec(
        app="clips-api",
        repo_full_name="acme/clips-api",
        workload_class="web",
        overrides=overrides,
        environments=[EnvSpec(
            name="dev", namespace="clips", project="example-project",
            cluster_name="sandbox", location="us-central1", gke_cluster="g",
            ar_repo="us-central1-docker.pkg.dev/example-project/apps",
            wif_provider="projects/1/locations/global/workloadIdentityPools/gojira/providers/github",
            gsa_email="clips-api-deploy@example-project.iam.gserviceaccount.com",
        )],
    )


def _deployment_resources(files):
    doc = yaml.safe_load(files["k8s/base/deployment.yaml"])
    return doc["spec"]["template"]["spec"]["containers"][0]["resources"]


def test_render_applies_overrides_over_class():
    ov = Overrides(requests={"cpu": "800m"}, limits={"cpu": "1250m"},
                   justification="cpu: p95 760m over 14d")
    res = _deployment_resources(render(_spec(ov)))
    assert res["requests"]["cpu"] == "800m"          # overridden
    assert res["limits"]["cpu"] == "1250m"           # overridden
    assert res["requests"]["memory"] == "256Mi"      # class default kept
    assert res["requests"]["ephemeral-storage"] == "4Gi"  # untouched


def test_render_without_overrides_is_class_defaults():
    res = _deployment_resources(render(_spec()))
    assert res["requests"]["cpu"] == "250m" and res["limits"]["cpu"] == "500m"


def test_read_overrides_parses_and_filters():
    text = """\
app: clips-api
class: web
overrides:
  requests: { cpu: "800m", gpu: "2" }
  limits: { cpu: "1250m" }
  justification: "measured"
"""
    ov = read_overrides(text)
    assert ov.requests == {"cpu": "800m"}     # gpu filtered out
    assert ov.limits == {"cpu": "1250m"}
    assert ov.justification == "measured"
    assert read_overrides("app: x\nclass: web\n") is None       # no block
    assert read_overrides(":\n bad: [") is None                 # unparseable


def test_apply_resource_overrides_textually():
    rendered = render(_spec())["k8s/base/deployment.yaml"]
    updated = apply_resource_overrides(
        rendered, requests={"cpu": "800m"}, limits={"cpu": "1250m", "memory": "768Mi"}
    )
    res = yaml.safe_load(updated)["spec"]["template"]["spec"]["containers"][0]["resources"]
    assert res["requests"]["cpu"] == "800m"
    assert res["limits"] == {"cpu": "1250m", "memory": "768Mi", "ephemeral-storage": "8Gi"}
    assert res["requests"]["memory"] == "256Mi"      # untouched
    assert updated.startswith("# Generated by Gojira")  # comments survive


def test_regeneration_with_overrides_is_idempotent():
    """The finding-8 lesson for sizing: render(spec-with-overrides) must equal
    what the sizing PR produced — so a later re-onboard doesn't revert it."""
    sized_by_pr = apply_resource_overrides(
        render(_spec())["k8s/base/deployment.yaml"],
        requests={"cpu": "800m"}, limits={"cpu": "1250m"},
    )
    ov = Overrides(requests={"cpu": "800m"}, limits={"cpu": "1250m"})
    regenerated = render(_spec(ov))["k8s/base/deployment.yaml"]
    assert regenerated == sized_by_pr