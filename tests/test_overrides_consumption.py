"""Overrides consumption: the justified escape hatch actually reshapes manifests.

Three seams: render() honors GeneratorSpec.overrides (so regeneration never
reverts sizing — the finding-8 lesson applied to sizing); read_overrides()
parses the gojira.yaml block defensively; apply_resource_overrides() rewrites
a generated deployment textually for the one-PR sizing flow.
"""

import yaml

from gojira.generator import (
    EnvSpec,
    GeneratorSpec,
    Overrides,
    apply_resource_overrides,
    read_overrides,
    render,
)


def _spec(overrides=None):
    return GeneratorSpec(
        app="clips-api",
        repo_full_name="acme/clips-api",
        workload_class="web",
        overrides=overrides,
        environments=[EnvSpec(
            name="dev", namespace="clips", project="example-project",
            cluster_name="sandbox", location="us-central1", gke_cluster="g",
            ar_repo="us-central1-docker.pkg.dev/example-project/apps",
            wif_provider="projects/1/locations/global/workloadIdentityPools/gojira/providers/github",
            gsa_email="clips-api-deploy@example-project.iam.gserviceaccount.com",
        )],
    )


def _deployment_resources(files):
    doc = yaml.safe_load(files["k8s/base/deployment.yaml"])
    return doc["spec"]["template"]["spec"]["containers"][0]["resources"]


def test_render_applies_overrides_over_class():
    ov = Overrides(requests={"cpu": "800m"}, limits={"cpu": "1250m"},
                   justification="cpu: p95 760m over 14d")
    res = _deployment_resources(render(_spec(ov)))
    assert res["requests"]["cpu"] == "800m"          # overridden
    assert res["limits"]["cpu"] == "1250m"           # overridden
    assert res["requests"]["memory"] == "256Mi"      # class default kept
    assert res["requests"]["ephemeral-storage"] == "4Gi"  # untouched


def test_render_without_overrides_is_class_defaults():
    res = _deployment_resources(render(_spec()))
    assert res["requests"]["cpu"] == "250m" and res["limits"]["cpu"] == "500m"


def test_read_overrides_parses_and_filters():
    text = """\
app: clips-api
class: web
overrides:
  requests: { cpu: "800m", gpu: "2" }
  limits: { cpu: "1250m" }
  justification: "measured"
"""
    ov = read_overrides(text)
    assert ov.requests == {"cpu": "800m"}     # gpu filtered out
    assert ov.limits == {"cpu": "1250m"}
    assert ov.justification == "measured"
    assert read_overrides("app: x\nclass: web\n") is None       # no block
    assert read_overrides(":\n bad: [") is None                 # unparseable


def test_apply_resource_overrides_textually():
    rendered = render(_spec())["k8s/base/deployment.yaml"]
    updated = apply_resource_overrides(
        rendered, requests={"cpu": "800m"}, limits={"cpu": "1250m", "memory": "768Mi"}
    )
    res = yaml.safe_load(updated)["spec"]["template"]["spec"]["containers"][0]["resources"]
    assert res["requests"]["cpu"] == "800m"
    assert res["limits"] == {"cpu": "1250m", "memory": "768Mi", "ephemeral-storage": "8Gi"}
    assert res["requests"]["memory"] == "256Mi"      # untouched
    assert updated.startswith("# Generated by Gojira")  # comments survive


def test_regeneration_with_overrides_is_idempotent():
    """The finding-8 lesson for sizing: render(spec-with-overrides) must equal
    what the sizing PR produced — so a later re-onboard doesn't revert it."""
    sized_by_pr = apply_resource_overrides(
        render(_spec())["k8s/base/deployment.yaml"],
        requests={"cpu": "800m"}, limits={"cpu": "1250m"},
    )
    ov = Overrides(requests={"cpu": "800m"}, limits={"cpu": "1250m"})
    regenerated = render(_spec(ov))["k8s/base/deployment.yaml"]
    assert regenerated == sized_by_pr

def test_rendered_gojira_yaml_round_trips_overrides():
    """Finding #10: the contract file must carry the overrides forward. If the
    template drops them, the next regeneration silently reverts to class
    defaults — read_overrides(render(...)) must reproduce spec.overrides."""
    ov = Overrides(requests={"cpu": "50m", "memory": "64Mi"},
                   limits={"cpu": "100m", "memory": "128Mi"},
                   justification='measured: p95 30m over 14d; "quoted" chars too')
    files = render(_spec(ov))
    back = read_overrides(files["gojira.yaml"])
    assert back == ov
    # and without overrides, the commented example remains for humans
    assert "# overrides:" in render(_spec())["gojira.yaml"]


# --- overrides.hpa: the app's own bounds over the class's scaling shape ------

def test_hpa_override_renders_bounds_and_memory_target():
    """A proxy that runs 30-500 replicas on CPU 60% and memory 70% is a web
    app with its own bounds, not a new class."""
    from gojira.generator import HpaOverride, Overrides

    ov = Overrides(hpa=HpaOverride(min=30, max=500, cpu=60, memory=70), justification="prod traffic")
    files = render(_spec(overrides=ov).model_copy(update={"workload_class": "web"}))
    hpa = yaml.safe_load(files["k8s/base/hpa.yaml"])
    assert hpa["spec"]["minReplicas"] == 30 and hpa["spec"]["maxReplicas"] == 500
    metrics = {m["resource"]["name"]: m["resource"]["target"]["averageUtilization"] for m in hpa["spec"]["metrics"]}
    assert metrics == {"cpu": 60, "memory": 70}
    assert "hpa: { min: 30, max: 500, cpu: 60, memory: 70 }" in files["gojira.yaml"]
    assert read_overrides(files["gojira.yaml"]).hpa == ov.hpa  # round trip


def test_hpa_override_partial_keeps_class_for_the_rest():
    from gojira.generator import HpaOverride, Overrides

    files = render(_spec(overrides=Overrides(hpa=HpaOverride(max=40), justification="x"))
                   .model_copy(update={"workload_class": "web"}))
    hpa = yaml.safe_load(files["k8s/base/hpa.yaml"])
    assert (hpa["spec"]["minReplicas"], hpa["spec"]["maxReplicas"]) == (2, 40)  # web min stays
    assert [m["resource"]["name"] for m in hpa["spec"]["metrics"]] == ["cpu"]  # no memory metric


def test_hpa_override_ignored_where_the_class_does_not_scale():
    """The agent class is one Socket Mode consumer; a bound cannot make it two."""
    from gojira.generator import HpaOverride, Overrides

    files = render(_spec(overrides=Overrides(hpa=HpaOverride(min=2, max=5), justification="x"))
                   .model_copy(update={"workload_class": "agent"}))
    assert "k8s/base/hpa.yaml" not in files


def test_read_overrides_hpa_rejects_junk():
    assert read_overrides("overrides:\n  hpa: { min: true, max: 5 }\n").hpa.min is None
    assert read_overrides("overrides:\n  hpa: { min: 10, max: 5 }\n").hpa is None   # min > max
    assert read_overrides("overrides:\n  hpa: { cpu: 150 }\n").hpa is None           # not a percent
    assert read_overrides("overrides:\n  hpa: nonsense\n").hpa is None


def test_rendered_strings_are_yaml_not_html():
    """'>' and non-ASCII survive as themselves in gojira.yaml and the
    Deployment's env — quoted for YAML, not escaped for a browser."""
    spec = _spec()
    spec.overrides = Overrides(
        requests={"cpu": "50m"}, justification="p99 45m over 14d; request 250m -> 50m — ok"
    )
    spec.env_vars = {"GREETING": "<hi> & bye"}
    out = render(spec)
    assert "\\u003e" not in out["gojira.yaml"] and "250m -> 50m — ok" in out["gojira.yaml"]
    assert "\\u003c" not in out["k8s/base/deployment.yaml"]
    assert read_overrides(out["gojira.yaml"]).justification == spec.overrides.justification
